/** "spf=50+; pa=++++; ff; actives=Niacinamide 10%, Zinc PCA 1%" → { specs, flags, typical } */
export function parseSpecs(text) {
  const specs = {}, flags = {};
  let typical = false;
  for (const part of String(text || '').split(';').map(s => s.trim()).filter(Boolean)) {
    const eq = part.indexOf('=');
    if (eq < 0) { flags[part] = true; continue; }
    const k = part.slice(0, eq).trim(), v = part.slice(eq + 1).trim();
    if (['__proto__', 'constructor', 'prototype'].includes(k)) continue;
    if (k === 'ref') { typical = v === 'typical'; continue; }
    specs[k] = v;
  }
  return { specs, flags, typical };
}

