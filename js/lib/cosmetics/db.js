/** Formulas that share the most ingredients (water and the most common helpers count for less). */
export function similarProducts(product, n = 6) {
  const weight = (name) => {
    const k = ingredientInfo(name)?.inci || name;
    const uses = INGREDIENT_INDEX.get(k)?.length || 1;
    return 1 / Math.log2(1 + uses);
  };
  const mine = new Map(product.inci.map(x => [ingredientInfo(x)?.inci || x, weight(x)]));
  const total = [...mine.values()].reduce((a, b) => a + b, 0) || 1;
  return PRODUCTS.filter(p => p.id !== product.id).map(p => {
    let shared = 0, count = 0;
    for (const x of p.inci) { const k = ingredientInfo(x)?.inci || x; if (mine.has(k)) { shared += mine.get(k); count++; } }
    return { product: p, score: shared / total + (p.category === product.category ? 0.08 : 0), shared: count };
  }).filter(s => s.shared >= 3).sort((a, b) => b.score - a.score).slice(0, n);
}

// "Crème", "creme" and "cream" are the same word to someone searching.
const tokens = (s) => norm(s).split(' ').filter(Boolean);
function score(hay, qt) {
  const h = norm(hay);
  if (!qt.length) return 0;
  let s = 0;
  for (const t of qt) {
    const i = h.indexOf(t);
    if (i < 0) return 0;
    s += (i === 0 || h[i - 1] === ' ') ? 2 : 1;
  }
  return s / qt.length + (h.startsWith(qt.join(' ')) ? 1 : 0);
}

/** Products, brands and ingredients matching the words typed, best first. */
export function search(query, { limit = 8 } = {}) {
  const qt = tokens(query);
  if (!qt.length) return { products: [], brands: [], ingredients: [] };
  const products = PRODUCTS.map(p => ({ p, s: p.code === String(query).trim() ? 10 : Math.max(score(`${p.brand} ${p.name}`, qt) * 1.2, score(`${p.name} ${p.type} ${CATEGORY_BY_ID[p.category]?.label}`, qt), score(`${p.brand} ${p.type}`, qt) * 0.9) }))
    .filter(x => x.s > 0).sort((a, b) => b.s - a.s || (b.p.year || 0) - (a.p.year || 0)).slice(0, limit).map(x => x.p);
  const brands = BRANDS.map(b => ({ b, s: Math.max(score(b.name, qt) * 1.3, score(`${b.name} ${b.parent} ${b.country}`, qt)) }))
    .filter(x => x.s > 0).sort((a, b) => b.s - a.s).slice(0, limit).map(x => x.b);
  const ingredients = Object.entries(INCI).map(([inci, info]) => ({ inci, info, s: Math.max(score(inci, qt) * 1.2, score(`${info.c} ${info.f}`, qt)) }))
    .filter(x => x.s > 0).sort((a, b) => b.s - a.s || (INGREDIENT_INDEX.get(b.inci)?.length || 0) - (INGREDIENT_INDEX.get(a.inci)?.length || 0)).slice(0, limit)
    .map(({ inci, info }) => ({ inci, info, uses: INGREDIENT_INDEX.get(inci) || [] }));
  return { products, brands, ingredients };
}

