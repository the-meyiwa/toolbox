/* ============================================================
   Chemical Compound Database.

   Three layers, searched together:
   1. Curated compounds grouped by field of use (pharmaceutical,
      agricultural, food, cosmetic, laboratory, industrial,
      materials, biochemical, toxic & hazardous), bundled.
   2. The full offline index (~76,000 compounds from PubChem-
      derived tables, CRC Handbook and safety sources), loaded
      on first search from public/data/compounds-extended.json.
   3. Live PubChem lookup for anything else, plus GHS hazard
      classifications, descriptions and structure images.

   Data is generated by scripts/build-compounds.py.
   ============================================================ */

import { COMPOUNDS_DATA, COMPOUND_FIELDS } from '../lib/compounds-dataset.js';
import { curatedCompoundIndex, loadExtendedIndex, searchIndex } from '../lib/compound-search.js';
import {
  searchPubChem, fetchCasNumber, fetchGhs, fetchDescription, structureImageUrl, pubchemPageUrl,
} from '../lib/pubchem.js';
import { calculateMolarMass } from '../lib/chemistry-engine.js';
import { escapeHtml } from '../lib/biz.js';
import { copyText } from '../utils.js';

const PAGE_SIZE = 36;
const EXTENDED_LIMIT = 200;
const FIELD_LABELS = {
  'Pharmaceutical': 'Pharmaceuticals',
  'Agricultural': 'Agricultural',
  'Food & Nutrition': 'Food & Nutrition',
  'Cosmetic & Personal Care': 'Cosmetics',
  'Laboratory Reagent': 'Lab Reagents',
  'Industrial': 'Industrial',
  'Materials': 'Materials',
  'Biochemical': 'Biochemistry',
  'Toxic & Hazardous': 'Toxic & Hazardous',
};

const fmtTemp = v => (v === undefined || v === null ? '—' : `${v} °C`);
const fmtDensity = v => (v === undefined || v === null ? '—' : `${v} g/cm³`);
const fmtMass = v => (v ? `${Number(v).toFixed(3)} g/mol` : '—');

function badge(text, tone = 'neutral') {
  const colors = tone === 'danger'
    ? 'background:rgba(220,38,38,0.08); color:var(--danger,#dc2626); border:1px solid rgba(220,38,38,0.35);'
    : 'background:var(--bg-subtle); color:var(--text-muted); border:1px solid var(--border);';
  return `<span style="font-size:0.72rem; font-weight:600; ${colors} padding:2px 8px; border-radius:999px; white-space:nowrap;">${escapeHtml(text)}</span>`;
}

function isHazardous(c) {
  return (c.fields || []).includes('Toxic & Hazardous')
    || (c.hazards || []).some(h => h.startsWith('IARC Group 1') || h.startsWith('NTP: known'));
}

function cardHtml(c, key) {
  const tags = (c.fields && c.fields.length ? c.fields : [c.category]).filter(Boolean);
  const hazards = c.hazards || [];
  return `
    <div class="tool-card" style="background:var(--bg-card); border:1px solid var(--border); border-radius:14px; padding:18px; display:flex; flex-direction:column; align-items:stretch; justify-content:space-between; gap:14px; min-width:0;">
      <div>
        <div style="display:flex; justify-content:space-between; align-items:flex-start; margin-bottom:8px; gap:10px;">
          <div style="min-width:0;">
            <div style="font-family:var(--mono); font-size:1.22rem; font-weight:700; color:var(--text); letter-spacing:-0.02em; word-break:break-all;">${escapeHtml(c.formula || '—')}</div>
            <div style="font-size:0.78rem; color:var(--text-muted); font-family:var(--mono); margin-top:2px;">${c.live ? 'Resolves from PubChem' : fmtMass(c.molarMass)}</div>
          </div>
          <div style="display:flex; flex-wrap:wrap; gap:4px; justify-content:flex-end;">
            ${isHazardous(c) ? badge('Hazardous', 'danger') : ''}
            ${badge(FIELD_LABELS[tags[0]] || tags[0] || 'Compound')}
          </div>
        </div>

        <h4 style="margin:0 0 4px; font-size:0.98rem; font-weight:700; color:var(--text); line-height:1.35;">${escapeHtml(c.name)}</h4>
        ${c.iupac ? `<div title="${escapeHtml(c.iupac)}" style="font-size:0.75rem; color:var(--text-muted); margin-bottom:10px; line-height:1.35; word-break:break-word; display:-webkit-box; -webkit-line-clamp:2; -webkit-box-orient:vertical; overflow:hidden;">${escapeHtml(c.iupac)}</div>` : ''}

        ${c.use ? `
          <div style="font-size:0.78rem; background:var(--bg-subtle); border-left:3px solid var(--accent, #007aff); padding:5px 10px; border-radius:0 6px 6px 0; margin-bottom:10px; color:var(--text); line-height:1.4;">
            ${escapeHtml(c.use)}
          </div>` : ''}

        ${c.live ? '' : `
          <div style="display:grid; grid-template-columns:repeat(2, 1fr); gap:6px; font-size:0.74rem; background:var(--bg-subtle); padding:10px 12px; border-radius:8px; border:1px solid var(--border);">
            <div><span style="color:var(--text-muted);">CAS:</span> <span style="font-family:var(--mono); color:var(--text);">${escapeHtml(c.cas || '—')}</span></div>
            <div><span style="color:var(--text-muted);">Density:</span> <span style="color:var(--text);">${fmtDensity(c.density)}</span></div>
            <div><span style="color:var(--text-muted);">Melting:</span> <span style="color:var(--text);">${fmtTemp(c.melt)}</span></div>
            <div><span style="color:var(--text-muted);">Boiling:</span> <span style="color:var(--text);">${fmtTemp(c.boil)}</span></div>
          </div>`}
      </div>

      <div style="display:flex; justify-content:space-between; align-items:center; border-top:1px solid var(--border); padding-top:12px; flex-wrap:wrap; gap:8px;">
        <span style="font-size:0.72rem; color:var(--text-muted); max-width:170px; overflow:hidden; text-overflow:ellipsis; white-space:nowrap;" title="${escapeHtml(hazards.join('; '))}">
          ${escapeHtml(hazards[0] || (c.extended ? 'Full index' : c.source === 'pubchem' ? 'PubChem' : ''))}
        </span>
        <div style="display:flex; gap:6px;">
          <button class="btn btn-primary btn-sm cd-details" data-key="${key}" style="font-size:0.72rem; padding:4px 10px;">Details</button>
          ${c.formula ? `<button class="btn btn-secondary btn-sm cd-copy-formula" data-formula="${escapeHtml(c.formula)}" style="font-size:0.72rem; padding:4px 10px;">Copy</button>` : ''}
        </div>
      </div>
    </div>`;
}

function propRow(label, value) {
  return `<div><div style="color:var(--text-muted); font-size:0.72rem;">${label}</div><div style="color:var(--text); font-size:0.86rem; word-break:break-word;">${value}</div></div>`;
}

export default {
  render(container) {
    this._cleanup = [];
    let activeField = 'all';
    let visibleCount = PAGE_SIZE;
    let extended = null;          // { index, total } once loaded
    let extendedError = null;
    let pubchemResults = null;    // results of an explicit PubChem search
    let shown = [];               // records currently rendered, addressed by index

    const fieldCounts = Object.fromEntries(COMPOUND_FIELDS.map(f => [f, 0]));
    for (const c of COMPOUNDS_DATA) for (const f of c.fields || []) fieldCounts[f]++;

    container.innerHTML = `
      <div class="tool-section" style="max-width:1200px; margin:0 auto;">
        <div style="background:var(--white); border:1px solid var(--g200); border-radius:12px; padding:16px 20px; margin-bottom:16px; display:flex; flex-wrap:wrap; align-items:center; justify-content:space-between; gap:12px;">
          <div style="display:flex; align-items:center; gap:12px;">
            <div style="width:40px; height:40px; border-radius:10px; background:var(--p50,var(--surface-2)); border:1px solid var(--p200,#bfdbfe); color:var(--p700,var(--text)); display:flex; align-items:center; justify-content:center; flex-shrink:0;">
              <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M21 16V8a2 2 0 0 0-1-1.73l-7-4a2 2 0 0 0-2 0l-7 4A2 2 0 0 0 3 8v8a2 2 0 0 0 1 1.73l7 4a2 2 0 0 0 2 0l7-4A2 2 0 0 0 21 16z"/></svg>
            </div>
            <div>
              <div style="font-weight:700; font-size:1.05rem; color:var(--black); letter-spacing:-0.01em;">Chemical Compound Database</div>
              <div style="font-size:0.82rem; color:var(--g600);">${COMPOUNDS_DATA.length.toLocaleString()} curated compounds by field, a 76,000-compound offline index, and live PubChem lookup for the rest.</div>
            </div>
          </div>
          <div style="display:inline-flex; align-items:center; gap:8px; background:var(--g50); border:1px solid var(--g200); padding:6px 14px; border-radius:100px; font-size:0.82rem; font-weight:600; color:var(--g800);">
            <span style="display:inline-block; width:8px; height:8px; border-radius:50%; background:var(--success);"></span>
            <span id="cd-counter-text"></span>
          </div>
        </div>

        <div style="display:flex; flex-direction:column; gap:12px; margin-bottom:18px;">
          <div style="display:flex; flex-wrap:wrap; gap:8px; align-items:center;" id="cd-cat-group">
            <button class="btn btn-sm is-active cd-cat-btn" data-cat="all" style="border-radius:100px; padding:6px 14px; font-weight:600; font-size:0.82rem; white-space:nowrap;">All</button>
            ${COMPOUND_FIELDS.map(f => `
              <button class="btn btn-sm cd-cat-btn" data-cat="${escapeHtml(f)}" style="border-radius:100px; padding:6px 14px; font-weight:600; font-size:0.82rem; white-space:nowrap;">
                ${escapeHtml(FIELD_LABELS[f] || f)} <span style="opacity:0.75; font-size:0.75rem; margin-left:4px;">(${fieldCounts[f]})</span>
              </button>`).join('')}
          </div>
          <div style="position:relative; width:100%;">
            <input type="text" id="cd-search" class="tool-input" placeholder="Search by name (e.g. glyphosate), formula (C8H9NO2), CAS number (50-78-2), use or hazard…" style="font-size:0.9rem; width:100%; height:44px; padding-left:40px; border-radius:10px;">
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" style="position:absolute; left:14px; top:13px; color:var(--g400); pointer-events:none;"><circle cx="11" cy="11" r="8"/><path d="m21 21-4.35-4.35"/></svg>
          </div>
          <div id="cd-note" style="font-size:0.78rem; color:var(--text-muted);"></div>
        </div>

        <div id="cd-grid" style="display:grid; grid-template-columns:repeat(auto-fill, minmax(300px, 1fr)); gap:14px;"></div>
        <div id="cd-footer" style="display:flex; flex-wrap:wrap; justify-content:center; gap:10px; margin-top:24px; padding-bottom:12px;"></div>
      </div>
    `;

    const catGroup = container.querySelector('#cd-cat-group');
    const searchIn = container.querySelector('#cd-search');
    const gridEl = container.querySelector('#cd-grid');
    const footerEl = container.querySelector('#cd-footer');
    const counterText = container.querySelector('#cd-counter-text');
    const noteEl = container.querySelector('#cd-note');

    const ensureExtended = () => {
      if (extended || extendedError) return;
      loadExtendedIndex()
        .then(result => { extended = result; renderCompounds(false); })
        .catch(err => { extendedError = err; renderCompounds(false); });
    };

    function currentMatches() {
      const query = searchIn.value.trim();
      const curated = searchIndex(curatedCompoundIndex(), query, { field: activeField });
      const more = query && activeField === 'all' && extended
        ? searchIndex(extended.index, query, { limit: EXTENDED_LIMIT })
        : [];
      return { query, curated, more };
    }

    function renderCompounds(resetVisible = true) {
      if (resetVisible) visibleCount = PAGE_SIZE;
      const { query, curated, more } = currentMatches();
      const all = pubchemResults ? pubchemResults : curated.concat(more);
      shown = all.slice(0, visibleCount);

      const indexTotal = extended ? `${extended.total.toLocaleString()} in full index` : '76,000+ in full index';
      counterText.innerHTML = pubchemResults
        ? `<strong>${pubchemResults.length}</strong> PubChem results`
        : query || activeField !== 'all'
          ? `<strong>${all.length.toLocaleString()}${more.length === EXTENDED_LIMIT ? '+' : ''}</strong> matches`
          : `<strong>${COMPOUNDS_DATA.length.toLocaleString()}</strong> curated · ${indexTotal}`;

      noteEl.textContent = pubchemResults
        ? 'Showing live results from PubChem.'
        : query && activeField === 'all' && !extended && !extendedError
          ? 'Loading the full offline index…'
          : extendedError && query
            ? 'The full offline index could not be loaded, so only curated compounds are searched.'
            : activeField !== 'all' && query
              ? 'Field filters search the curated set. Choose All to include the full index.'
              : '';

      if (!all.length) {
        renderEmpty(query);
      } else {
        gridEl.innerHTML = shown.map((c, i) => cardHtml(c, i)).join('');
      }

      const remaining = all.length - shown.length;
      footerEl.innerHTML = `
        ${remaining > 0 ? `<button id="cd-load-more" class="btn btn-secondary" style="font-weight:600; padding:10px 24px; border-radius:100px; font-size:0.88rem;">Load more (${remaining.toLocaleString()} remaining)</button>` : ''}
        ${query && !pubchemResults ? `<button id="cd-pubchem" class="btn btn-secondary" style="font-weight:600; padding:10px 24px; border-radius:100px; font-size:0.88rem;">Search PubChem for “${escapeHtml(query)}”</button>` : ''}
        ${pubchemResults ? '<button id="cd-back" class="btn btn-secondary" style="font-weight:600; padding:10px 24px; border-radius:100px; font-size:0.88rem;">Back to offline results</button>' : ''}
      `;
    }

    function renderEmpty(query) {
      let formulaCard = '';
      try {
        const calc = calculateMolarMass(query);
        formulaCard = `
          <div class="tool-card" style="background:var(--bg-card); border:1px solid var(--border); border-radius:14px; padding:20px; grid-column:1/-1;">
            <div style="display:flex; justify-content:space-between; align-items:baseline; margin-bottom:8px; flex-wrap:wrap; gap:8px;">
              <span style="font-family:var(--mono); font-size:1.4rem; font-weight:700; color:var(--text);">${escapeHtml(query)}</span>
              <span style="font-family:var(--mono); font-size:1.1rem; font-weight:700; color:var(--accent, #007aff);">${calc.molarMass.toFixed(3)} g/mol</span>
            </div>
            <p style="font-size:0.84rem; color:var(--text-muted); margin:0 0 14px;">Not in the offline database. Molar mass calculated from standard atomic weights.</p>
            <div style="display:flex; flex-wrap:wrap; gap:8px;">
              ${calc.composition.map(it => `
                <span style="font-size:0.78rem; background:var(--bg-subtle); border:1px solid var(--border); padding:4px 10px; border-radius:6px; color:var(--text);">
                  <strong>${it.name} (${it.symbol}):</strong> ${it.percent.toFixed(1)}% (${it.count} atom${it.count > 1 ? 's' : ''})
                </span>`).join('')}
            </div>
          </div>`;
      } catch { /* not a formula */ }

      gridEl.innerHTML = formulaCard || `
        <div style="grid-column:1/-1; text-align:center; padding:48px 16px; background:var(--bg-card); border:1px dashed var(--border); border-radius:14px;">
          <p style="font-size:0.95rem; font-weight:600; color:var(--text); margin-bottom:4px;">${pubchemResults ? 'PubChem has no compound' : 'No offline compounds'} matching “${escapeHtml(query)}”</p>
          <p style="font-size:0.82rem; color:var(--text-muted); margin:0;">Try a generic name, trade name, formula or CAS number${pubchemResults ? '' : ', or search PubChem below'}.</p>
        </div>`;
    }

    async function runPubChemSearch() {
      const query = searchIn.value.trim();
      if (!query) return;
      const btn = footerEl.querySelector('#cd-pubchem');
      if (btn) { btn.disabled = true; btn.textContent = 'Searching PubChem…'; }
      try {
        pubchemResults = await searchPubChem(query, { limit: 12 });
        renderCompounds(true);
      } catch {
        if (btn) { btn.disabled = false; btn.textContent = 'PubChem is unreachable. Try again'; }
      }
    }

    /* ---------------------------------------------------------- details */
    function openDetails(c) {
      const overlay = document.createElement('div');
      overlay.style.cssText = 'position:fixed; inset:0; z-index:1600; background:rgba(0,0,0,0.45); display:flex; align-items:flex-start; justify-content:center; padding:24px 16px; overflow-y:auto;';
      overlay.setAttribute('role', 'dialog');
      overlay.setAttribute('aria-modal', 'true');
      overlay.setAttribute('aria-label', c.name);
      document.body.appendChild(overlay);

      const close = () => {
        overlay.remove();
        document.removeEventListener('keydown', onKey, true);
      };
      // Capture phase so Escape closes the dialog without also leaving the tool.
      const onKey = e => {
        if (e.key !== 'Escape') return;
        e.stopPropagation();
        close();
      };
      document.addEventListener('keydown', onKey, true);
      overlay.addEventListener('click', e => { if (e.target === overlay || e.target.closest('[data-close]')) close(); });
      this._cleanup.push(close);

      const draw = (record, live = {}) => {
        const fields = (record.fields || []).map(f => badge(FIELD_LABELS[f] || f, f === 'Toxic & Hazardous' ? 'danger' : 'neutral')).join(' ');
        const ghs = live.ghs;
        overlay.innerHTML = `
          <div style="background:var(--bg-card, var(--white)); color:var(--text); border:1px solid var(--border); border-radius:16px; width:min(720px, 100%); padding:22px; box-shadow:0 20px 60px rgba(0,0,0,0.25);">
            <div style="display:flex; justify-content:space-between; gap:12px; align-items:flex-start;">
              <div style="min-width:0;">
                <h3 style="margin:0; font-size:1.25rem; line-height:1.3;">${escapeHtml(record.name)}</h3>
                <div style="font-family:var(--mono); color:var(--text-muted); margin-top:4px;">${escapeHtml(record.formula || '')} ${record.molarMass ? `· ${fmtMass(record.molarMass)}` : ''}</div>
              </div>
              <button class="btn btn-secondary btn-sm" data-close aria-label="Close">Close</button>
            </div>
            ${fields ? `<div style="display:flex; flex-wrap:wrap; gap:6px; margin-top:10px;">${fields}</div>` : ''}
            ${record.use ? `<p style="margin:12px 0 0; font-size:0.9rem;">${escapeHtml(record.use)}</p>` : ''}

            <div style="display:grid; grid-template-columns:${record.cid ? 'minmax(0,1fr) 180px' : '1fr'}; gap:16px; margin-top:16px; align-items:start;">
              <div style="display:grid; grid-template-columns:repeat(auto-fill, minmax(150px, 1fr)); gap:10px 16px;">
                ${propRow('CAS number', `<span style="font-family:var(--mono);">${escapeHtml(record.cas || live.cas || '—')}</span>`)}
                ${propRow('PubChem CID', record.cid ? `<a href="${pubchemPageUrl(record.cid)}" target="_blank" rel="noopener noreferrer">${record.cid}</a>` : '—')}
                ${propRow('Melting point', fmtTemp(record.melt))}
                ${propRow('Boiling point', fmtTemp(record.boil))}
                ${propRow('Density', fmtDensity(record.density))}
                ${propRow('Flash point', fmtTemp(record.flash))}
                ${record.iupac ? `<div style="grid-column:1/-1;">${propRow('IUPAC name', escapeHtml(record.iupac))}</div>` : ''}
                ${record.synonyms?.length ? `<div style="grid-column:1/-1;">${propRow('Also known as', escapeHtml(record.synonyms.join(', ')))}</div>` : ''}
              </div>
              ${record.cid ? `<img src="${structureImageUrl(record.cid)}" alt="Structure of ${escapeHtml(record.name)}" loading="lazy" style="width:180px; height:180px; object-fit:contain; background:#fff; border:1px solid var(--border); border-radius:10px;" onerror="this.style.display='none'">` : ''}
            </div>

            ${(record.hazards || []).length ? `
              <h4 style="margin:18px 0 6px; font-size:0.9rem;">Hazard data (offline)</h4>
              <ul style="margin:0; padding-left:18px; font-size:0.85rem; line-height:1.5;">${record.hazards.map(h => `<li>${escapeHtml(h)}</li>`).join('')}</ul>` : ''}

            ${record.handling ? `
              <h4 style="margin:18px 0 6px; font-size:0.9rem;">Safe handling</h4>
              <p style="margin:0; font-size:0.85rem; line-height:1.5; background:rgba(220,38,38,0.06); border-left:3px solid var(--danger,#dc2626); padding:8px 12px; border-radius:0 8px 8px 0;">${escapeHtml(record.handling)}</p>` : ''}

            <h4 style="margin:18px 0 6px; font-size:0.9rem;">GHS classification (PubChem)</h4>
            <div style="font-size:0.85rem; line-height:1.5;">
              ${live.loading ? '<span style="color:var(--text-muted);">Loading live data from PubChem…</span>'
                : live.error ? `<span style="color:var(--text-muted);">${escapeHtml(live.error)}</span>`
                : !record.cid ? '<span style="color:var(--text-muted);">No PubChem record to look up.</span>'
                : !ghs ? '<span style="color:var(--text-muted);">PubChem lists no GHS classification for this compound.</span>'
                : `
                  ${ghs.signal ? `<div style="margin-bottom:6px;"><strong>Signal word:</strong> ${escapeHtml(ghs.signal)}</div>` : ''}
                  ${ghs.pictograms.length ? `<div style="display:flex; flex-wrap:wrap; gap:6px; margin-bottom:8px;">${ghs.pictograms.map(p => badge(p, 'danger')).join('')}</div>` : ''}
                  <ul style="margin:0; padding-left:18px;">${ghs.statements.map(s => `<li>${escapeHtml(s)}</li>`).join('')}</ul>`}
            </div>

            ${live.description ? `
              <h4 style="margin:18px 0 6px; font-size:0.9rem;">Description</h4>
              <p style="margin:0; font-size:0.85rem; line-height:1.55;">${escapeHtml(live.description.text)}</p>
              ${live.description.source ? `<div style="font-size:0.72rem; color:var(--text-muted); margin-top:4px;">Source: ${escapeHtml(live.description.source)} via PubChem</div>` : ''}` : ''}

            <p style="margin:18px 0 0; font-size:0.72rem; color:var(--text-muted);">Reference information only. Always follow the supplier's safety data sheet and local regulations.</p>
          </div>`;
      };

      const loadLive = async () => {
        let record = { ...c };
        draw(record, { loading: true });
        try {
          if (!record.cid) {
            const [hit] = await searchPubChem(record.name, { limit: 1 });
            if (!hit) { draw(record, { error: 'PubChem has no record under this name.' }); return; }
            record = { ...hit, ...record, cid: hit.cid, formula: hit.formula, molarMass: hit.molarMass, iupac: hit.iupac, live: false };
          }
          const [ghs, description, cas] = await Promise.all([
            fetchGhs(record.cid),
            fetchDescription(record.cid).catch(() => null),
            record.cas ? Promise.resolve(record.cas) : fetchCasNumber(record.cid).catch(() => null),
          ]);
          if (overlay.isConnected) draw({ ...record, cas }, { ghs, description, cas });
        } catch {
          if (overlay.isConnected) draw(record, { error: 'PubChem is unreachable right now, so live hazard data is unavailable.' });
        }
      };
      loadLive();
    }

    /* ---------------------------------------------------------- events */
    catGroup.addEventListener('click', e => {
      const btn = e.target.closest('[data-cat]');
      if (!btn) return;
      for (const b of catGroup.querySelectorAll('.cd-cat-btn')) b.classList.toggle('is-active', b === btn);
      activeField = btn.dataset.cat;
      pubchemResults = null;
      renderCompounds(true);
    });

    let debounce;
    searchIn.addEventListener('input', () => {
      pubchemResults = null;
      if (searchIn.value.trim()) ensureExtended();
      clearTimeout(debounce);
      debounce = setTimeout(() => renderCompounds(true), 120);
    });
    searchIn.addEventListener('keydown', e => {
      if (e.key === 'Enter' && !gridEl.querySelector('.cd-details')) runPubChemSearch();
    });
    this._cleanup.push(() => clearTimeout(debounce));

    gridEl.addEventListener('click', e => {
      const details = e.target.closest('.cd-details');
      if (details) { openDetails.call(this, shown[Number(details.dataset.key)]); return; }
      const copy = e.target.closest('.cd-copy-formula');
      if (copy) copyText(copy.dataset.formula, copy);
    });

    footerEl.addEventListener('click', e => {
      if (e.target.closest('#cd-load-more')) { visibleCount += PAGE_SIZE; renderCompounds(false); }
      else if (e.target.closest('#cd-pubchem')) runPubChemSearch();
      else if (e.target.closest('#cd-back')) { pubchemResults = null; renderCompounds(true); }
    });

    renderCompounds(true);
  },

  destroy() {
    for (const fn of this._cleanup ?? []) fn();
    this._cleanup = [];
  },
};
