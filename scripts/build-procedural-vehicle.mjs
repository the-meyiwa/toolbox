#!/usr/bin/env node
/**
 * Generates Toolbox-original procedural vehicle packages (GLB + manifest +
 * specification sheet) and registers them in public/automobile/catalog.json.
 *
 *   node scripts/build-procedural-vehicle.mjs            # build all
 *   node scripts/build-procedural-vehicle.mjs --check    # verify committed output is up to date
 *
 * Output is deterministic: running the generator twice produces identical bytes.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCorolla } from './procedural-vehicle/corolla-model.mjs';
import { E170, E140 } from './procedural-vehicle/corolla-profiles.mjs';
import { describeComponent, specSheet, GENERATIONS, LAYERS } from './procedural-vehicle/corolla-data.mjs';
import { writeGLB } from './procedural-vehicle/geometry.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GENERATOR = 'toolbox-procedural-vehicle@1.0.0';
const REPO = 'https://github.com/the-meyiwa/toolbox';

const PACKAGES = [
  {
    gen: 'e170', profile: E170,
    vehicle: { id: 'toyota-corolla-2014-2016', make: 'Toyota', model: 'Corolla', displayName: '2014–2016 Toyota Corolla', year: null, years: [2014, 2015, 2016], generation: 'Eleventh generation (E170, North America)', variant: 'Sedan · L / LE / LE Eco / S grades', bodyStyle: 'Sedan', accuracy: 'representative' },
    aliases: ['Corolla', 'Toyota Corolla', 'E170', 'ZRE172', '2014', '2015', '2016', 'Corolla 2014', 'Corolla 2015', 'Corolla 2016', 'Corolla LE', 'Corolla S'],
    specifications: { bodyStyle: 'Sedan', layout: 'Front-engine, front-wheel drive', engine: { code: '2ZR-FE 1.8 L I4 (2ZR-FAE on LE Eco)' }, transmission: { code: '6MT · 4AT (L) · CVTi-S' }, curbWeight: 'About 2,800 lb (LE / S)', wheelbase: '106.3 in (2,700 mm)' }
  },
  {
    gen: 'e140', profile: E140,
    vehicle: { id: 'toyota-corolla-2013', make: 'Toyota', model: 'Corolla', displayName: '2013 Toyota Corolla', year: 2013, years: [2013], generation: 'Tenth generation (E140, North America)', variant: 'Sedan · L / LE / S grades', bodyStyle: 'Sedan', accuracy: 'representative' },
    aliases: ['Corolla', 'Toyota Corolla', 'E140', 'ZRE142', '2013', 'Corolla 2013', 'Corolla LE', 'Corolla S'],
    specifications: { bodyStyle: 'Sedan', layout: 'Front-engine, front-wheel drive', engine: { code: '2ZR-FE 1.8 L I4' }, transmission: { code: '5MT · 4AT' }, curbWeight: '2,635–2,767 lb', wheelbase: '102.4 in (2,600 mm)' }
  }
];

function validateArticulations(articulations, componentIds, pivots) {
  const ids = new Set();
  for (const a of articulations) {
    if (ids.has(a.id)) throw new Error(`Duplicate articulation ${a.id}`);
    ids.add(a.id);
    a.components = a.components.filter(c => componentIds.has(c));
    if (!a.components.length) throw new Error(`Articulation ${a.id} targets no components`);
    for (const t of a.transforms) if (!pivots.has(t.node)) throw new Error(`Articulation ${a.id} references missing node ${t.node}`);
  }
  for (const a of articulations) for (const r of a.requires || []) if (!ids.has(r.id)) throw new Error(`Articulation ${a.id} requires unknown ${r.id}`);
  return articulations;
}

async function buildPackage(def) {
  const { assembly, articulations } = buildCorolla(def.profile);
  const glb = writeGLB([assembly.root], { generator: GENERATOR });
  const sha256 = crypto.createHash('sha256').update(glb.bytes).digest('hex');
  const componentIds = new Set(assembly.componentIds());
  const components = [...componentIds].sort().map(id => describeComponent(id, def.gen));
  const pivots = new Set(assembly.pivots.keys());
  const arts = validateArticulations(articulations, componentIds, pivots);
  const g = GENERATIONS[def.gen];
  const dir = path.join(ROOT, 'public/automobile/packages', def.vehicle.id);
  const manifest = {
    schemaVersion: 1,
    packageVersion: '1.0.0',
    vehicle: def.vehicle,
    license: {
      spdx: 'LicenseRef-Toolbox-Original', creator: 'Toolbox',
      sourceUrl: `${REPO}/blob/Beta/scripts/build-procedural-vehicle.mjs`, licenseUrl: REPO,
      attribution: `Procedural ${g.title} model generated by Toolbox from published dimensions and specifications`
    },
    layers: [{ id: 'complete', label: 'Body, cabin and mechanical', glb: 'vehicle.glb', available: true, triangles: glb.triangles, sha256 }],
    layerGroups: LAYERS.filter(layer => components.some(c => c.layer === layer.id)),
    components,
    meshMappings: assembly.mappings,
    articulations: arts,
    specSheet: 'specs.json',
    notes: `Procedural model of the ${g.market} ${g.title} (${g.code}). Overall length, width, height, wheelbase, track and tyre size follow published figures; body surfacing, trim shapes and the placement of engine-bay and cabin components are Toolbox approximations for orientation. Hinges, slides and removable parts are articulated at their real pivot locations.`,
    ingestion: { tool: 'scripts/build-procedural-vehicle.mjs', generator: GENERATOR, outputTriangles: glb.triangles, meshes: glb.meshes, nodes: glb.nodes }
  };
  const specs = specSheet(def.gen);
  const catalogEntry = {
    id: def.vehicle.id, make: 'Toyota', model: 'Corolla', year: def.vehicle.year, years: g.years,
    generation: def.vehicle.generation, variant: def.vehicle.variant, bodyStyle: 'Sedan',
    aliases: def.aliases, manifest: `/automobile/packages/${def.vehicle.id}/manifest.json`,
    specSheet: `/automobile/packages/${def.vehicle.id}/specs.json`, specifications: def.specifications
  };
  return { dir, glb, manifest, specs, catalogEntry };
}

const check = process.argv.includes('--check');
const built = [];
for (const def of PACKAGES) built.push(await buildPackage(def));

const catalogPath = path.join(ROOT, 'public/automobile/catalog.json');
const catalog = JSON.parse(await readFile(catalogPath, 'utf8'));
const generatedIds = new Set(built.map(b => b.catalogEntry.id));
catalog.vehicles = [...built.map(b => b.catalogEntry), ...catalog.vehicles.filter(v => !generatedIds.has(v.id))];
catalog.defaultVehicleId = 'toyota-corolla-2014-2016';

const files = [];
for (const b of built) {
  files.push([path.join(b.dir, 'vehicle.glb'), Buffer.from(b.glb.bytes)]);
  files.push([path.join(b.dir, 'manifest.json'), JSON.stringify(b.manifest, null, 2) + '\n']);
  files.push([path.join(b.dir, 'specs.json'), JSON.stringify(b.specs, null, 2) + '\n']);
}
files.push([catalogPath, JSON.stringify(catalog, null, 2) + '\n']);

if (check) {
  const stale = [];
  for (const [file, content] of files) {
    const current = await readFile(file).catch(() => null);
    if (!current || !current.equals(Buffer.from(content))) stale.push(path.relative(ROOT, file));
  }
  if (stale.length) { console.error('Out of date:\n  ' + stale.join('\n  ')); process.exitCode = 1; }
  else console.log('Procedural vehicle packages are up to date.');
} else {
  for (const [file, content] of files) { await mkdir(path.dirname(file), { recursive: true }); await writeFile(file, content); }
  for (const b of built) console.log(JSON.stringify({ package: b.manifest.vehicle.id, triangles: b.glb.triangles, bytes: b.glb.bytes.length, components: b.manifest.components.length, articulations: b.manifest.articulations.length, sha256: b.manifest.layers[0].sha256 }));
}
